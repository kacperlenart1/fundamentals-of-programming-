###
# Program wykonujący podstawowe operacje arytmetyczne 
# i wyświetlający wyrażenia oraz ich wyniki za pomocą f-stringów.
#

a = 3
b = 5

# Wyświetlenie działań i wyników z użyciem f-stringów
print(f'{a} + {b} = {a + b}')
print(f'{a} - {b} = {a - b}')
print(f'{a} * {b} = {a * b}')
print(f'{a} / {b} = {a / b}')