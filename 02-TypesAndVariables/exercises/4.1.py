###
# Wyświetlanie danych osobowych studenta przy użyciu f-stringów( to jakby zmienne w nawiasach klamrowych)
#

name = "Adam"
age = 19      # Wiek studenta 
height = 180 # Wzrost w cm 

# Wyświetlenie danych z użyciem f-stringów
print(f"My name is {name}.")
print(f"I am {age} years old, and my height is {height} cm.")
print(f"In 6 years I will be {age + 6} years old.")