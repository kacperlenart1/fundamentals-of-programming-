### PLIK 1.7.py: Kompletny program wypisujący listę zakupów, każdy produkt w osobnej linii.
shopping_list = [  # Lista produktów spożywczych z treści zadania.
    "milk", "bread", "eggs", "butter", "cheese",
    "tomatoes", "potatoes", "carrots", "onions", "garlic"
]  # Koniec listy zakupów.

for item in shopping_list:  # Iterujemy po każdym elemencie listy zakupów.
    print(item)  # Wypisujemy każdy produkt w osobnej linii.
