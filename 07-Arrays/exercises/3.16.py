### PLIK 3.16.py: Kompletny program wypisujący wartości "Seven" oraz 30 ze wskazanej krotki.
nested_tuple = ("Seven", [10, 20, 30], (5, 15, 25))  # Krotka zawierająca napis, listę oraz krotkę.
print(nested_tuple[0])  # Wypisujemy element "Seven".
print(nested_tuple[1][2])  # Wypisujemy wartość 30 z wewnętrznej listy.
